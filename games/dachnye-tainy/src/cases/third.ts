/**
 * Третье дело: умеренное усложнение поверх того же движка. Два новых
 * элемента сразу — четвёртая сущность в каждой категории (было 3×3,
 * стало 4×4) и упорядоченная категория «время» с отношениями before
 * и adjacent, которых не было ни в tutorial-1, ни в second-1.
 * Дело всё ещё решается пошаговым рассуждением без перебора и догадок —
 * проверяется тем же validateCase()/deduceCase(), что и первые два.
 *
 * Первая версия этого дела связывала Бориса и Вику одной adjacent-уликой
 * без направления — Борис и Вика могли поменяться местами и временем
 * одновременно, ничего в остальных уликах это не запрещало.
 * countSolutions() честно поймал это как ambiguous ещё на этапе автора,
 * до того как дело увидел игрок; после замены этой улики на before
 * решение стало единственным. Так дело и должно проверяться: не
 * «выглядит решаемым на глаз», а countSolutions() === 1 и
 * deduceCase().solved === true.
 */

