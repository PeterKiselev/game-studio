/**
 * Сетка судоку — плоский массив из 81 клетки, индекс = row*9+col, 0 = пусто.
 * Плоский массив, а не number[][]: проще сравнивать на равенство в тестах
 * и сериализовать в сохранение без вложенной структуры.
 */
export type Grid = number[];

export type Difficulty = 'easy' | 'medium' | 'hard';

export interface Puzzle {
  /** Начальная расстановка, которую видит игрок (0 — пустая клетка). */
  givens: Grid;
  /** Полное решение — эталон для проверки, не показывается игроку напрямую. */
  solution: Grid;
  difficulty: Difficulty;
  /** Seed, из которого пазл сгенерирован — нужен для повторной генерации того же пазла. */
  seed: string;
}
