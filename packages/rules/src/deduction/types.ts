/**
 * Сюжетные логические задачи («кто где был, что принёс»).
 *
 * Модель намеренно однородная: все категории — это множества значений
 * одинаковой мощности, а решение — взаимно однозначное соответствие
 * между ними. Из этого следует главное упрощение: ссылка на сущность
 * не обязана быть именем персонажа. Пара «категория + значение»
 * определяет сущность однозначно, поэтому «Ирина» и «владелец зонта» —
 * ссылки одного вида, и движку не нужно их различать.
 */

/** Категория сущностей: персонажи, места, предметы, время. */
export interface Category {
  id: string;
  /** Подпись для интерфейса. */
  title: string;
  /**
   * Значения. Для упорядоченных категорий порядок в массиве значим:
   * индекс значения — это его позиция (утро < полдень < вечер).
   */
  values: string[];
  /**
   * Значения выстроены в линию: время, порядок прихода, места за столом.
   * Только для таких категорий работают отношения before, after и adjacent.
   */
  ordered?: boolean;
}

/** Ссылка на сущность через любую её характеристику. */
export interface Ref {
  category: string;
  value: string;
}

export type ClueKind =
  /** Одна и та же сущность: «пирог принёс тот, кто был в беседке». */
  | 'same'
  /** Разные сущности: «Ирина зонт не брала». */
  | 'different'
  /** a раньше b в упорядоченной категории. */
  | 'before'
  /** a позже b — зеркальное before, отдельный вид ради читаемости улики. */
  | 'after'
  /** Соседние позиции в упорядоченной категории (разница в одну). */
  | 'adjacent';

export interface Clue {
  kind: ClueKind;
  a: Ref;
  b: Ref;
  /**
   * Упорядоченная категория для before, after и adjacent.
   * Можно не указывать, если упорядоченная категория в деле одна —
   * тогда она подставляется сама. Валидатор ругается, если таких
   * категорий ноль или больше одной.
   */
  order?: string;
  /** Текст улики, который читает игрок. Пишется автором дела. */
  text: string;
}

export interface Case {
  id: string;
  title: string;
  /** Категория-якорь: по ней строится сетка в интерфейсе. Обычно персонажи. */
  anchor: string;
  categories: Category[];
  clues: Clue[];
  /** Текст развязки, который открывается после раскрытия. */
  epilogue: string;
  /**
   * Вступление перед уликами: что случилось и какой вопрос задаёт дело.
   * Только для интерфейса — движок его не читает. Необязательно: у первых
   * шести дел вступления нет.
   */
  intro?: string;
  /**
   * Находка, которую игрок получает после раскрытия и которая ведёт к
   * следующему делу главы. Только для интерфейса.
   */
  finding?: { title: string; text: string };
  /**
   * Иллюстрированное вступление: кадры перед делом. Только атмосфера, не
   * улики — условия задачи остаются в `intro`, кадры можно пропустить.
   * Только для интерфейса.
   */
  story?: StoryFrame[];
  /**
   * Шаг после сетки: «чьи слова расходятся с фактами?». Только для
   * интерфейса — показания НЕ улики, в солвер не входят и проверяются
   * сверкой с уже найденным решением.
   */
  contradiction?: Contradiction;
}

export interface StoryFrame {
  /** Адрес картинки (собранный бандлером). */
  image: string;
  /** Описание для экранного чтения. */
  alt: string;
  /** Подпись под картинкой: две-три строки. */
  caption: string;
}

/** Слова персонажа: «я был там-то». Верно или нет — решает решение сетки, а не автор. */
export interface Testimony {
  /** Кто говорит — значение категории-якоря. */
  who: Ref;
  /** Что он о себе утверждает: «я был в бане» = { место, баня }. */
  claim: Ref;
  /** Реплика, которую читает игрок. */
  text: string;
}

export interface Contradiction {
  question: string;
  /**
   * Что именно в показаниях проверяют таблицы — «о месте в 20:00». Объяснение
   * неверного ответа подтверждает только это, а не реплику целиком: остальное
   * в словах персонажа (ключ в кармане, «весь вечер») таблица не устанавливает.
   */
  claimTopic: string;
  testimonies: Testimony[];
  /** Что открывается после верного ответа, до развязки. */
  resolution: string;
}

/**
 * Решение: для каждой категории — какое её значение досталось каждой
 * сущности якоря. solution[categoryId][anchorIndex] = valueIndex.
 * Якорь тоже присутствует и всегда тождественен (solution[anchor][i] === i) —
 * это позволяет искать сущность по любой категории одинаковым кодом.
 */
export type Solution = Record<string, number[]>;

/** Отметка игрока в сетке. */
export type MarkValue = 'yes' | 'no';

/** Состояние сетки у игрока. Ключи строит markKey. */
export type PlayerMarks = Record<string, MarkValue>;

/**
 * Почему движок сделал этот вывод.
 *
 * Для правил, опирающихся на уже установленную связь, в причине лежит
 * сама эта пара, а не одно значение из неё: объяснение обязано показать
 * игроку, какая именно связь закрыла клетку. Иначе подсказка учит
 * неправильно — а игра ровно про то, чтобы учить рассуждению.
 */
export type HintReason =
  /** Прямо следует из улики. */
  | { rule: 'clue'; clueIndex: number }
  /** Клетка закрыта уже установленной парой. */
  | { rule: 'taken'; pair: [Ref, Ref] }
  /** Остался единственный возможный вариант. */
  | { rule: 'last-option' }
  /** Связь перенесена через установленную пару. */
  | { rule: 'transitive'; link: [Ref, Ref] }
  /** Не остаётся места в упорядоченной категории. */
  | { rule: 'order'; clueIndex: number };

/** Один шаг рассуждения. */
export interface Deduction {
  a: Ref;
  b: Ref;
  /** true — «это точно они», false — «это точно не они». */
  positive: boolean;
  reason: HintReason;
  /**
   * Готовое объяснение по-русски. Структура в reason оставлена рядом,
   * чтобы интерфейс мог сформулировать иначе или перевести, не трогая движок.
   */
  text: string;
}